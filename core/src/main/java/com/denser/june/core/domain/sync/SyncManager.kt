/**
 * Providers report media file names with a casing we do not control, so lookups are
 * case-insensitive. Collecting the remote listing into a lowercase set once turns what used
 * to be a linear scan per file (O(files x remote entries) per pass) into a single O(1) lookup.
 *
 * Media file names are generated by June itself and are ASCII only, so lowercasing is an
 * equivalent normalisation here.
 */
private fun Collection<String>.toNormalisedNameSet(): Set<String> =
    mapTo(HashSet(size + size / 4 + 1)) { it.lowercase() }

@OptIn(ExperimentalCoroutinesApi::class)
sealed class SyncStatus {
    data object Idle : SyncStatus()
    data object Preparing : SyncStatus()
    data class Syncing(
        val progress: Float = 0f,
        val uploadCount: Int = 0,
        val downloadCount: Int = 0,
        val totalOperations: Int = 0,
        val currentOperation: String = ""
    ) : SyncStatus()

    data object Success : SyncStatus()
    data object Dirty : SyncStatus()
    data class Error(val message: String) : SyncStatus()
}

